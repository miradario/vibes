  const outcomes=await Promise.allSettled([insert(a,2),insert(b,3)]);
  assert.equal(outcomes.filter(x=>x.status==='fulfilled').length,1,'exactly one last-seat reservation wins');
  assert.match(outcomes.find(x=>x.status==='rejected').reason.message,/cupos/);
  const winner=outcomes[0].status==='fulfilled'?a:b,winningUser=outcomes[0].status==='fulfilled'?2:3;
