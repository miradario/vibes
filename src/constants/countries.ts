const countryByCode = new Map(COUNTRIES.map(country => [country.code, country]));
export const isCountryCode = (value: unknown): value is string =>
  typeof value === "string" && countryByCode.has(value);
export const getCountryName = (code: string | null | undefined, locale = "es-AR") => {
  const country = code ? countryByCode.get(code) : undefined;
  return country ? (locale.startsWith("en") ? country.en : country.es) : "";
};
export const searchCountries = (query: string, locale = "es-AR") => {
  const normalize = (value: string) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();
  const term = normalize(query);
  return COUNTRIES.filter(country => normalize(country.es + " " + country.en + " " + country.code).includes(term))
    .map(country => ({ code: country.code, label: getCountryName(country.code, locale) }))
    .sort((a, b) => a.label.localeCompare(b.label, locale));
};
